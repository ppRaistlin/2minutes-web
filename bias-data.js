function getBiasForDomain(hostname) {
  const clean = hostname.replace(/^www\./, "").toLowerCase();
  const parts = clean.split(".");
  // Essai domaine complet, puis domaine racine
  const rootDomain = parts.slice(-2).join(".");
  const thirdLevel = parts.length > 2 ? parts.slice(-3).join(".") : null;
  return (
    BIAS_DATABASE[clean] ||
    (thirdLevel ? BIAS_DATABASE[thirdLevel] : null) ||
    BIAS_DATABASE[rootDomain] ||
    null
  );
}

